using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Archives;
using Mutagen.Bethesda.Environments;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Cache;
using Mutagen.Bethesda.Skyrim;

namespace SkyrimAutoDiag
{
    public class CompatibleSkyrimPatcher
    {
        private static readonly ModKey PatchModKey = ModKey.FromNameAndExtension("AutoDiagPatch.esp");

        public int BuildCompatiblePatch(string dataFolderPath, bool generateSpidIni = true)
        {
            int patchedRecordsCount = 0;
            var spidLines = new List<string>
            {
                "; Auto-generated by Skyrim AE Diagnostics Suite (SPID Compatible Distribution)",
                $"; Generated on {DateTime.Now:yyyy-MM-dd HH:mm:ss}"
            };

            // Alle vorhandenen BSA-Archive einmalig für die schnelle FaceGen-Suche \u00F6ffnen
            var bsaReaders = LoadAllBsaReaders(dataFolderPath);

            using var env = GameEnvironment.Typical.Skyrim(SkyrimRelease.SkyrimSE);

            var activeLoadOrder = env.LoadOrder.PriorityOrder
                .Where(listing => listing.ModKey != PatchModKey)
                .ToList();

            var linkCache = activeLoadOrder.ToImmutableLinkCache();

            var patchMod = new SkyrimMod(PatchModKey, SkyrimRelease.SkyrimSE);
            patchMod.ModHeader.Flags |= SkyrimModHeader.HeaderFlag.Small;
            patchMod.ModHeader.Stats.Version = 1.71f;

            // 1. NPC Black-Face-Bug Merger (Prüft jetzt Loose Files UND .bsa Archive!)
            foreach (var npcContext in activeLoadOrder.Npc().WinningContextOverrides())
            {
                var formKey = npcContext.Record.FormKey;
                var allContexts = linkCache.ResolveAllSimpleContexts<INpcGetter>(formKey).ToList();
                if (allContexts.Count <= 1) continue;

                var faceGenProvider = allContexts.FirstOrDefault(ctx =>
                    HasFaceGenMeshLooseOrBsa(dataFolderPath, ctx.ModKey, formKey, bsaReaders));
                if (faceGenProvider == null) continue;

                var winningNpc = npcContext.Record;
                var visualNpc = faceGenProvider.Record;

                bool hasVisualConflict = !winningNpc.HeadParts.SequenceEqual(visualNpc.HeadParts)
                                         || !Equals(winningNpc.HeadTexture, visualNpc.HeadTexture);

                if (hasVisualConflict)
                {
                    var patchedNpc = patchMod.Npcs.GetOrAddAsOverride(winningNpc);
                    patchedNpc.HeadParts.Clear();
                    patchedNpc.HeadParts.AddRange(visualNpc.HeadParts);
                    patchedNpc.HeadTexture.SetTo(visualNpc.HeadTexture);
                    patchedNpc.TextureLighting = visualNpc.TextureLighting;
                    patchedNpc.FaceMorph = visualNpc.FaceMorph?.DeepCopy();
                    patchedNpc.FaceParts = visualNpc.FaceParts?.DeepCopy();
                    patchedNpc.TintLayers.Clear();
                    patchedNpc.TintLayers.AddRange(visualNpc.TintLayers.Select(t => t.DeepCopy()));
                    patchedRecordsCount++;

                    if (generateSpidIni && !winningNpc.DefaultOutfit.IsNull)
                    {
                        spidLines.Add($"; Visual + Outfit sync for {winningNpc.EditorID ?? formKey.ToString()}");
                        spidLines.Add($"Outfit = 0x{winningNpc.DefaultOutfit.FormKey.ID:X}~{winningNpc.DefaultOutfit.FormKey.ModKey.FileName}|0x{formKey.ID:X}~{formKey.ModKey.FileName}");
                    }
                }
            }

            // 2. Leveled Item (LVLI) Merger
            foreach (var lvliContext in activeLoadOrder.LeveledItem().WinningContextOverrides())
            {
                var formKey = lvliContext.Record.FormKey;
                var allContexts = linkCache.ResolveAllSimpleContexts<ILeveledItemGetter>(formKey).ToList();
                if (allContexts.Count <= 1) continue;

                var winningLvli = lvliContext.Record;
                var allEntries = allContexts
                    .Where(c => c.Record.Entries != null)
                    .SelectMany(c => c.Record.Entries!)
                    .Where(e => e.Data != null && !e.Data.Reference.IsNull)
                    .GroupBy(e => (e.Data!.Reference.FormKey, e.Data.Level, e.Data.Count))
                    .Select(g => g.First())
                    .ToList();

                int currentCount = winningLvli.Entries?.Count ?? 0;
                if (allEntries.Count > currentCount)
                {
                    var patchedLvli = patchMod.LeveledItems.GetOrAddAsOverride(winningLvli);
                    patchedLvli.Entries ??= new Noggog.ExtendedList<LeveledItemEntry>();
                    patchedLvli.Entries.Clear();
                    foreach (var entry in allEntries)
                        patchedLvli.Entries.Add(entry.DeepCopy());
                    patchedRecordsCount++;
                }
            }

            // 3. Container (CONT) Merger
            foreach (var contContext in activeLoadOrder.Container().WinningContextOverrides())
            {
                var formKey = contContext.Record.FormKey;
                var allContexts = linkCache.ResolveAllSimpleContexts<IContainerGetter>(formKey).ToList();
                if (allContexts.Count <= 1) continue;

                var winningCont = contContext.Record;
                var allItems = allContexts
                    .Where(c => c.Record.Items != null)
                    .SelectMany(c => c.Record.Items!)
                    .Where(i => !i.Item.Item.IsNull)
                    .GroupBy(i => i.Item.Item.FormKey)
                    .Select(g => g.OrderByDescending(x => x.Item.Count).First())
                    .ToList();

                int currentCount = winningCont.Items?.Count ?? 0;
                if (allItems.Count > currentCount)
                {
                    var patchedCont = patchMod.Containers.GetOrAddAsOverride(winningCont);
                    patchedCont.Items ??= new Noggog.ExtendedList<ContainerEntry>();
                    patchedCont.Items.Clear();
                    foreach (var item in allItems)
                        patchedCont.Items.Add(item.DeepCopy());
                    patchedRecordsCount++;
                }
            }

            string outputPath = Path.Combine(dataFolderPath, PatchModKey.FileName);
            patchMod.WriteToBinary(outputPath, new Mutagen.Bethesda.Plugins.Binary.Parameters.BinaryWriteParameters
            {
                ModKey = Mutagen.Bethesda.Plugins.Binary.Parameters.ModKeyOption.NoCheck
            });

            if (generateSpidIni)
            {
                string spidPath = Path.Combine(dataFolderPath, "AutoDiag_DISTR.ini");
                File.WriteAllLines(spidPath, spidLines, Encoding.UTF8);
            }

            return patchedRecordsCount;
        }

        private List<IArchiveReader> LoadAllBsaReaders(string dataFolderPath)
        {
            var list = new List<IArchiveReader>();
            if (!Directory.Exists(dataFolderPath)) return list;

            foreach (var bsaFile in Directory.GetFiles(dataFolderPath, "*.bsa"))
            {
                try
                {
                    list.Add(Archive.CreateReader(GameRelease.SkyrimSE, bsaFile));
                }
                catch { }
            }
            return list;
        }

        private bool HasFaceGenMeshLooseOrBsa(
            string dataFolder,
            ModKey modKey,
            FormKey npcFormKey,
            List<IArchiveReader> bsaReaders)
        {
            string hexId = $"00{npcFormKey.ID:X6}";
            string relFolder = Path.Combine(
                "meshes", "actors", "character", "facegendata", "facegeom", modKey.FileName);
            string fileName = $"{hexId}.nif";

            // 1. Prüfe Loose File im Data-Ordner
            string loosePath = Path.Combine(dataFolder, relFolder, fileName);
            if (File.Exists(loosePath)) return true;

            // 2. Prüfe alle geladenen .bsa-Archive
            foreach (var reader in bsaReaders)
            {
                if (reader.TryGetFolder(relFolder, out var folder))
                {
                    if (folder.Files.Any(f => string.Equals(
                            Path.GetFileName(f.Path), fileName, StringComparison.OrdinalIgnoreCase)))
                    {
                        return true;
                    }
                }
            }
            return false;
        }
    }
}